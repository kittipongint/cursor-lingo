#!/usr/bin/env python3
"""Generates core/en_model.inc: a quantised English letter-trigram model.

Sources: the system word list (/usr/share/dict/web2, plus simple inflections so that endings
like -s / -ed / -ing are represented) and, optionally, any English prose you point it at
(directories or files, e.g. documentation) so that common words weigh more than rare ones.
Only derived numbers are stored, never words.

    python3 tools/gen-en-model.py [corpus-dir-or-file ...] > core/en_model.inc
"""
import math, os, re, sys
from collections import Counter

words = set()
for path in ("/usr/share/dict/web2", "/usr/share/dict/web2a", "/usr/share/dict/propernames"):
    try:
        for line in open(path, encoding="latin-1"):
            w = line.strip().lower()
            if 2 <= len(w) <= 20 and re.fullmatch(r"[a-z]+", w):
                words.add(w)
    except OSError:
        pass
if len(words) < 50000:
    sys.exit("word list not found")

freq = Counter()
for root in sys.argv[1:]:
    paths = [root] if os.path.isfile(root) else [
        os.path.join(d, f) for d, ds, fs in os.walk(root) if "node_modules" not in d and "/." not in d
        for f in fs if f.endswith((".md", ".txt", ".rst"))]
    for path in paths:
        try:
            text = open(path, encoding="utf-8", errors="ignore").read()
        except OSError:
            continue
        for tok in re.findall(r"[A-Za-z]+", text):
            if 2 <= len(tok) <= 20 and (tok.islower() or tok.istitle()):
                freq[tok.lower()] += 1

def forms(w):
    yield w
    yield w + "s"
    if w.endswith("e"):
        yield w + "d"; yield w[:-1] + "ing"
    else:
        yield w + "ed"; yield w + "ing"

idx = lambda c: 0 if c == "^" else ord(c) - 96  # '^' and '$' share index 0
tri = Counter()
def add(f, weight):
    s = "^^" + f + "$"
    for i in range(len(s) - 2):
        tri[(idx(s[i]), idx(s[i + 1]), idx(s[i + 2]) if s[i + 2] != "$" else 0)] += weight

for w in words:
    for f in forms(w):
        add(f, 1.0)
for w, c in freq.items():
    if c >= 3 and re.fullmatch(r"[a-z]+", w):  # frequent tokens only: drops identifiers / typos
        add(w, 4.0 * math.log(c))

K = 0.05
out = []
for a in range(27):
    for b in range(27):
        tot = sum(tri[(a, b, c)] for c in range(27)) + K * 27
        for c in range(27):
            p = (tri[(a, b, c)] + K) / tot
            out.append(min(255, round(-math.log(p) * 16)))  # cost in 1/16 nat

print("// Generated by tools/gen-en-model.py - do not edit.")
print("// kEnCost[(a*27+b)*27+c] = -16*ln P(c | a b); 0 = word boundary, 1..26 = a..z.")
print("static const unsigned char kEnCost[27 * 27 * 27] = {")
for i in range(0, len(out), 27):
    print("  " + ",".join(map(str, out[i:i + 27])) + ",")
print("};")
